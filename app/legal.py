"""Plain-language terms and privacy pages. Reviewed wording is the owner's responsibility."""
from html import escape

from .config import settings

CSS = "body{font:16px/1.65 system-ui,sans-serif;max-width:720px;margin:6vh auto;padding:0 20px;color:#14203a}h1{font-size:28px}h2{font-size:18px;margin-top:28px}"


def _page(title: str, body: str) -> str:
    return f"<!doctype html><html lang=en><meta charset=utf-8><meta name=viewport content='width=device-width,initial-scale=1'><title>{escape(title)}</title><style>{CSS}</style><body>{body}</body></html>"


def contact() -> str:
    return escape(settings.contact_email or settings.admin_email)


